import { createHash } from "node:crypto";

import {
  MAX_NODES,
  SECTION_KEYS,
  SECTION_LABELS,
} from "./constants.mjs";

const LABEL_TO_KEY = new Map(
  Object.entries(SECTION_LABELS).flatMap(([key, labels]) =>
    labels.map((label) => [label.trim().toLowerCase(), key]),
  ),
);
const AGENT_HASH_RE = /<!--\s*agent-hash:([0-9a-f]{8})\s*-->\s*$/i;
const AGENT_MARKER_RE = /<!--\s*agent\s*-->\s*$/i;

export class ContextMapParseError extends Error {
  constructor(code) {
    super(code);
    this.name = "ContextMapParseError";
    this.code = code;
  }
}

function normalize(text) {
  return String(text)
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/^\[[ xX]\]\s*/, "")
    .replace(/^\*\*(high|medium|low)\*\*\s+/i, "")
    .replace(/[`*_]/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase()
    .replace(/[.。]+$/, "");
}

function fingerprint(text, checked = false) {
  const input = `${checked ? "1" : "0"}:${String(text)}`;
  let hash = 0x811c9dc5;
  for (let index = 0; index < input.length; index += 1) {
    hash ^= input.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(16).padStart(8, "0");
}

function stableId(parts) {
  return createHash("sha256").update(parts.join("\u001f")).digest("hex").slice(0, 16);
}

function indentationWidth(indent) {
  let width = 0;
  for (const character of indent) width += character === "\t" ? 4 : 1;
  return width;
}

function sectionForLabel(label) {
  return LABEL_TO_KEY.get(String(label).trim().toLowerCase()) ?? null;
}

function buildNode(rawText, section, parentId, occurrence) {
  let text = rawText;
  let storedHash = null;
  const hashMatch = text.match(AGENT_HASH_RE);
  if (hashMatch) {
    storedHash = hashMatch[1].toLowerCase();
    text = text.replace(AGENT_HASH_RE, "").trim();
  }
  const hasAgentMarker = AGENT_MARKER_RE.test(text);
  if (hasAgentMarker) text = text.replace(AGENT_MARKER_RE, "").trim();

  let checked = false;
  let taskState = null;
  if (section === "tasks") {
    const checkbox = text.match(/^\[([ xX])\]\s+(.*)$/);
    if (checkbox) {
      checked = checkbox[1].toLowerCase() === "x";
      taskState = checked ? "done" : "open";
      text = checkbox[2].trim();
    } else {
      taskState = "open";
    }
  }

  const riskMatch = section === "risks"
    ? text.match(/^\*\*(high|medium|low)\*\*\s+(.*)$/i)
    : null;
  const risk = riskMatch ? riskMatch[1].toLowerCase() : null;
  if (riskMatch) text = riskMatch[2].trim();

  const origin = hasAgentMarker &&
    (!storedHash || storedHash === fingerprint(text, checked))
    ? "agent"
    : "user";
  const id = stableId([section, parentId, normalize(text), String(occurrence)]);

  return {
    id,
    section,
    text,
    taskState,
    risk,
    excluded: section === "excluded",
    origin,
    children: [],
  };
}

export function parseRenderTree(markdown) {
  if (!markdown || !String(markdown).trim()) {
    throw new ContextMapParseError("EMPTY");
  }

  const root = {
    id: "context-map",
    section: "root",
    text: "Context Map",
    taskState: null,
    risk: null,
    excluded: false,
    origin: "user",
    children: [],
  };
  const sections = new Map();
  let currentSection = null;
  let depthWidths = [0];
  let stack = [];
  let nodeCount = 0;

  for (const rawLine of String(markdown).split(/\r?\n/)) {
    const trimmed = rawLine.trim();
    if (/^-{3,}\s*$/.test(trimmed) || /^\*Generated by Handoff Protocol/.test(trimmed)) break;
    if (!trimmed || /^<!--[\s\S]*-->\s*$/.test(trimmed) || /^#\s/.test(trimmed)) continue;

    const heading = trimmed.match(/^##\s+(.+?)\s*$/);
    if (heading && !trimmed.startsWith("###")) {
      currentSection = sectionForLabel(heading[1]);
      depthWidths = [0];
      stack = [];
      if (currentSection && !sections.has(currentSection)) {
        const sectionNode = {
          id: `section-${currentSection}`,
          section: currentSection,
          text: SECTION_LABELS[currentSection][0],
          taskState: null,
          risk: null,
          excluded: currentSection === "excluded",
          origin: "user",
          children: [],
        };
        sections.set(currentSection, sectionNode);
      }
      continue;
    }
    if (!currentSection) continue;

    const item = rawLine.match(/^(\s*)(?:[-*]|\d+[.)])\s+(.+?)\s*$/);
    if (!item) continue;
    const width = indentationWidth(item[1]);
    while (depthWidths.length > 1 && width < depthWidths.at(-1)) depthWidths.pop();
    if (width > depthWidths.at(-1)) depthWidths.push(width);
    const depth = depthWidths.length - 1;
    stack = stack.slice(0, depth);

    const parent = depth === 0 ? sections.get(currentSection) : stack[depth - 1];
    if (!parent) continue;
    const normalizedText = normalize(item[2]);
    const occurrence = parent.children.filter((node) => normalize(node.text) === normalizedText).length;
    const node = buildNode(item[2], currentSection, parent.id, occurrence);
    parent.children.push(node);
    stack[depth] = node;
    nodeCount += 1;
    if (nodeCount > MAX_NODES) throw new ContextMapParseError("TOO_MANY_NODES");
  }

  root.children = SECTION_KEYS.map((key) => sections.get(key)).filter(
    (section) => section && section.children.length > 0,
  );
  if (root.children.length === 0) throw new ContextMapParseError("INVALID");

  return { root, nodeCount };
}
